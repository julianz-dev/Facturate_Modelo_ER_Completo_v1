                )
            ),
            CONVERT(DECIMAL(14,2), f.cantidad * p.precio_venta)
        FROM @DetalleFuente AS f
        INNER JOIN dbo.ventas AS v
            ON v.uuid_local = f.uuid_local
        INNER JOIN dbo.productos AS p
            ON p.codigo_producto = f.codigo_producto;

        IF @@ROWCOUNT <> 1200
